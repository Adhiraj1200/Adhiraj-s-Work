string = input(str("Enter a string:"))
print(string)
for word in string:
    if word == "a":
        print("a")
        
    if word == "e":
        print("e")
        
    if word == "i":
        print("i")
        
    if word == "o":
        print("o")
        
    if word == "u":
        print("u")    